"""Test the change of the fixed point ``h*`` by changing only the input ``x``.

Use the same ``components`` of the ``fixed_point`` experiment,
except for the fact there are multiple inputs generated by the
same ``SEED`` value. 
"""
import numpy as np

from heartbrain import brain


# Constants
INPUT_SIZE = 3
HIDDEN_SIZE = 4

SEED = 42

N_STEPS = 50

N_INPUTS = 4


def main(): 

    rng = np.random.default_rng(SEED)

    # Inputs
    inputs = rng.normal( size=(N_INPUTS, INPUT_SIZE) )     

    # Random weights
    params = brain.init_params(input_size=INPUT_SIZE, hidden_size=HIDDEN_SIZE, rng=rng)

    # Inputs
    inputs_trajectories = []
    
    for i in range(N_INPUTS):
        # The first state "h0" is a vector of zeros by convention.
        h = brain.init_h0(HIDDEN_SIZE)
        
        x = inputs[i]
        trajectory = _run_single_experiment(x, params, h, N_STEPS)
        
        inputs_trajectories.append( (x,trajectory))

    # Logs
    for i, (x, trajectory) in enumerate(inputs_trajectories):
        _print_trajectory(i, N_INPUTS, x, trajectory)
    
    _print_summary(inputs_trajectories)


def _run_single_experiment(x: np.ndarray, params: brain.VanillaRNNParams, h_0: np.ndarray, n_steps: int) -> list[np.ndarray]:
    """Run the cell from ``h_0`` for ``n_steps`` with fixed ``x``. Returns the trajectory."""
    trajectory = [h_0]
    h = h_0
    for _ in range(1, n_steps):
        h = brain.cell_forward(x, h, params)
        trajectory.append(h)
    return trajectory


# === Log Functions ===
def _print_trajectory(index: int, total: int, x: np.ndarray, trajectory: list[np.ndarray]) -> None:
    """Print one experiment's trajectory with a header line."""
    print(f"\n==== Experiment {index+1}/{total} — x = {np.array2string(x, precision=4)} ====")
    for t, h in enumerate(trajectory):
        h_str = ", ".join(f"{xi:+.4f}" for xi in h)
        if t == 0:
            distance_str = "-"
        else:
            distance_str = f"{np.linalg.norm(h - trajectory[t-1]):.6f}"
        print(f"t={t:3d}   h = [{h_str}]   |dh| = {distance_str}")


def _print_summary(inputs_trajectories: list[tuple[np.ndarray, list[np.ndarray]]]) -> None:
    """Print a compact summary mapping each input to its final hidden state."""
    print("\n==== Summary ====")
    for i, (x, trajectory) in enumerate(inputs_trajectories):
        h_star = trajectory[-1]
        x_str = np.array2string(x, precision=4)
        h_str = np.array2string(h_star, precision=4)
        print(f"x_{i} = {x_str}   ->   h* = {h_str}")


if __name__ == '__main__':
    main()